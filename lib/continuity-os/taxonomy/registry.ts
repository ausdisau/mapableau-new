export function listLifeEventTypes(): LifeEventTypeSummary[] {
  return REGISTRY.map((item) => ({
    code: item.code,
    category: item.category,
    version: item.version,
    title: item.title,
    plainLanguageDescription: item.plainLanguageDescription,
  }));
}

export function getLifeEventType(
  code: LifeEventTypeCode
): LifeEventTypeDefinition | undefined {
  return BY_CODE.get(code);
}

export function requireLifeEventType(code: string): LifeEventTypeDefinition {
  const found = BY_CODE.get(code as LifeEventTypeCode);
  if (!found) {
    throw new Error(`UNSUPPORTED_LIFE_EVENT_TYPE:${code}`);
  }
  return found;
}

export function listLifeEventTypeCodes(): LifeEventTypeCode[] {
  return REGISTRY.map((item) => item.code);
}

