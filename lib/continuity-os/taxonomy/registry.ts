function def(
  partial: Omit<
    LifeEventTypeDefinition,
    "version" | "prohibitedAutomatedDecisions" | "reviewOwner"
  > &
    Partial<
      Pick<
        LifeEventTypeDefinition,
        "prohibitedAutomatedDecisions" | "reviewOwner" | "version"
      >
    >
): LifeEventTypeDefinition {
  return {
    version: partial.version ?? "1.0.0",
    reviewOwner: partial.reviewOwner ?? "continuity-os-product",
    prohibitedAutomatedDecisions: partial.prohibitedAutomatedDecisions ?? [
      "assign_worker",
      "book_transport",
      "cancel_service",
      "approve_refund",
      "determine_clinical_readiness",
      "determine_legal_eligibility",
      "close_incident",
      "override_access_passport",
    ],
    ...partial,
  };
}

